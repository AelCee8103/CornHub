create table public.watchlists (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    movie_id integer not null,
    title text not null,
    poster_path text,
    vote_average numeric(4, 2),
    release_date date,
    created_at timestamptz not null default now(),
    unique (user_id, movie_id)
);

create table public.playlists (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    name text not null check (char_length(trim(name)) > 0),
    description text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table public.playlist_items (
    id bigint generated by default as identity primary key,
    playlist_id bigint not null references public.playlists(id) on delete cascade,
    movie_id integer not null,
    title text not null,
    poster_path text,
    vote_average numeric(4, 2),
    release_date date,
    created_at timestamptz not null default now(),
    unique (playlist_id, movie_id)
);

create index watchlists_user_id_idx on public.watchlists(user_id);
create index playlists_user_id_idx on public.playlists(user_id);
create index playlist_items_playlist_id_idx on public.playlist_items(playlist_id);

alter table public.watchlists enable row level security;
alter table public.playlists enable row level security;
alter table public.playlist_items enable row level security;

create policy "Users manage their own watchlist"
on public.watchlists for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users manage their own playlists"
on public.playlists for all
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

create policy "Users manage items in their playlists"
on public.playlist_items for all
using (
    exists (
        select 1 from public.playlists
        where playlists.id = playlist_items.playlist_id
        and playlists.user_id = auth.uid()
    )
)
with check (
    exists (
        select 1 from public.playlists
        where playlists.id = playlist_items.playlist_id
        and playlists.user_id = auth.uid()
    )
);
